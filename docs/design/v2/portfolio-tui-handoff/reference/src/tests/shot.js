const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch();
  const errs = [];
  const mk = async (w,h,scheme) => { const p = await b.newPage({viewport:{width:w,height:h},colorScheme:scheme}); p.on('console',m=>m.type()==='error'&&errs.push(m.text())); p.on('pageerror',e=>errs.push('PAGEERR '+e.message)); await p.goto('file:///home/claude/tui/test.html'); await p.waitForTimeout(1800); return p; };
  let p = await mk(1280,820,'dark');
  console.log('overflow', await p.evaluate(()=>document.documentElement.scrollWidth-innerWidth), 'skin', await p.evaluate(()=>document.documentElement.dataset.skin));
  await p.screenshot({path:'a-top.png'});
  await p.evaluate(()=>document.querySelectorAll('.is-pending').forEach(e=>e.classList.remove('is-pending')));
  await p.screenshot({path:'a-full.png',fullPage:true});
  await p.keyboard.press('t'); await p.waitForTimeout(300);
  await p.keyboard.press('ArrowDown'); await p.keyboard.press('ArrowDown'); await p.keyboard.press('ArrowDown'); await p.waitForTimeout(400);
  await p.screenshot({path:'b-themes.png'});
  await p.keyboard.press('Enter'); await p.waitForTimeout(500);
  console.log('after commit skin', await p.evaluate(()=>document.documentElement.dataset.skin));
  await p.keyboard.press('Control+k'); await p.waitForTimeout(300); await p.keyboard.type('exp'); await p.screenshot({path:'c-palette.png'});
  await p.keyboard.press('Escape');
  await p.keyboard.press('/'); await p.keyboard.type('/th'); await p.waitForTimeout(200); await p.screenshot({path:'d-menu.png'});
  await p.keyboard.press('Escape'); await p.keyboard.press('Escape');
  await p.focus('#cmd'); await p.keyboard.type('react'); await p.keyboard.press('Enter'); await p.waitForTimeout(900);
  console.log('asks', await p.evaluate(()=>document.querySelectorAll('#asks .turn').length));
  await p.screenshot({path:'e-ask.png'});
  await p.keyboard.type('/lang es'); await p.keyboard.press('Enter'); await p.waitForTimeout(400);
  console.log('lang', await p.evaluate(()=>document.documentElement.lang));
  await p.keyboard.press('Escape');
  await p.goto('file:///home/claude/tui/test.html#design-system'); await p.waitForTimeout(800);
  await p.screenshot({path:'f-ds.png'});
  await p.click('#tab-components'); await p.waitForTimeout(300); await p.screenshot({path:'g-comp.png',fullPage:true});
  let m = await mk(390,780,'light');
  console.log('m overflow', await m.evaluate(()=>document.documentElement.scrollWidth-innerWidth), await m.evaluate(()=>document.documentElement.dataset.skin));
  await m.screenshot({path:'h-mobile.png'});
  await m.evaluate(()=>document.querySelectorAll('.is-pending').forEach(e=>e.classList.remove('is-pending')));
  await m.screenshot({path:'i-mobile-full.png',fullPage:true});
  console.log('errors', JSON.stringify(errs));
  await b.close();
})();
